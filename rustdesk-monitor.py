def fmt_duration(secs):
    if secs < 60:
        return f"{int(secs)}s"
    if secs < 3600:
        return f"{int(secs // 60)}m{int(secs % 60)}s"

    h = int(secs // 3600)
    m = int((secs % 3600) // 60)
    return f"{h}h{m}m"

def fmt_rate(bps):
    if bps is None:
        return "—"
    if bps < 1024:
        return f"{bps:.0f}B"
    if bps < 1024 * 1024:
        return f"{bps / 1024:.1f}K"
    return f"{bps / 1024 / 1024:.1f}M"

