def ansi_center(s, width):
    pad = width - ansi_len(s)
    if pad <= 0:
        return s

    left = pad // 2
    return " " * left + s + " " * (pad - left)

def trunc(s, w):
    if w <= 1:
        return ""

    mx = w - 1
    if len(s) <= mx:
        return s
    if mx < 10:
        return s[:mx]

    h = (mx - 3) // 2
    return s[:h] + "..." + s[-(mx - 3 - h) :]

